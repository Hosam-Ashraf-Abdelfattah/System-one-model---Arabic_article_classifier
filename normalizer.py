import re  # مكتبة التعبيرات النمطية، نستخدمها للبحث عن أنماط في النص وحذفها

class ArabicNormalizer:  # نعرّف class مسؤولة عن شيء واحد فقط: توحيد أشكال النص العربي
    def __init__(self):  # دالة التجهيز، تعمل مرة واحدة عند إنشاء الكائن
        self.strip_pattern = re.compile(r"[\u064B-\u0652\u0670\u0640]")  # نمط يطابق التشكيل (الفتحة والضمة...) وألف الخنجر والتطويل، وسنحذفها
        mapping = {"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ى": "ي"}  # جدول الاستبدال: أشكال الألف تصير ا، والألف المقصورة تصير ي
        for i, d in enumerate("٠١٢٣٤٥٦٧٨٩"):  # نمر على الأرقام الهندية ومعها ترتيبها من 0 إلى 9
            mapping[d] = str(i)  # نضيف للجدول تحويل كل رقم هندي إلى رقمه العادي
        self.char_map = str.maketrans(mapping)  # نحوّل الجدول إلى صيغة تفهمها بايثون لتبديل الحروف بسرعة
        self.space_pattern = re.compile(r"\s+")  # نمط يطابق أي تتابع من المسافات أو الأسطر الجديدة

    def __call__(self, text):  # تُنفَّذ عند كتابة normalizer(text)، وتستقبل نصاً وتعيده موحّداً
        text = self.strip_pattern.sub("", text)  # نحذف التشكيل والتطويل من النص
        text = text.translate(self.char_map)  # نبدّل الحروف والأرقام حسب الجدول الذي جهّزناه
        text = text.lower()  # نحوّل الحروف اللاتينية إلى صغيرة، ولا تأثير لها على العربية
        text = self.space_pattern.sub(" ", text)  # نحوّل كل تتابع مسافات أو أسطر إلى مسافة واحدة
        return text.strip()  # نحذف المسافات من أول النص وآخره ونعيده

if __name__ == "__main__":  # هذا الجزء يعمل فقط عند تشغيل الملف مباشرة، وليس عند استيراده من ملف آخر
    from datasets import load_from_disk  # نستورد دالة قراءة البيانات المحفوظة
    norm = ArabicNormalizer()  # ننشئ كائناً من الـ class، وهنا تعمل __init__
    print(norm("الْعَرَبِيَّةُ لُغَةٌ جَمِيلَةٌ"))  # اختبار التشكيل، والمتوقع: العربية لغة جميلة
    print(norm("أحمد ذهب إلى آخر الشارع ٢٠٢٦"))  # اختبار الألف والأرقام، والمتوقع: احمد ذهب الي اخر الشارع 2026
    print(norm("جـــميل   جدا\n\nجدا"))  # اختبار التطويل والمسافات، والمتوقع: جميل جدا جدا
    train = load_from_disk("data/sanad_split")["train"]  # نقرأ جزء التدريب الذي حفظناه سابقاً
    article = train[0]["Article"]  # نأخذ نص أول مقال
    print(article[:150])  # نطبع أول 150 حرفاً قبل التطبيع
    print(norm(article)[:150])  # ونطبع نفس الجزء بعد التطبيع لنقارن بأعيننا
